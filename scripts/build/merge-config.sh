# Merge layered Buildroot Kconfig fragments into a deduplicated .config file.

set -euo pipefail

usage() {
  cat <<'EOF'
Usage: merge-config.sh --profile <core|standard|extended> --output <file> [--experimental <name>] [--repo-root <dir>]
EOF
}

PROFILE=""
OUTPUT=""
EXPERIMENTAL=""
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --profile)
      [[ $# -ge 2 ]] || { echo "Error: --profile requires an argument" >&2; exit 2; }
      PROFILE="$2"
      shift 2
      ;;
    --output)
      [[ $# -ge 2 ]] || { echo "Error: --output requires an argument" >&2; exit 2; }
      OUTPUT="$2"
      shift 2
      ;;
    --experimental)
      [[ $# -ge 2 ]] || { echo "Error: --experimental requires an argument" >&2; exit 2; }
      EXPERIMENTAL="$2"
      shift 2
      ;;
    --repo-root)
      [[ $# -ge 2 ]] || { echo "Error: --repo-root requires an argument" >&2; exit 2; }
      REPO_ROOT="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Error: unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ -z "$PROFILE" || -z "$OUTPUT" ]]; then
  echo "Error: --profile and --output are required" >&2
  usage >&2
  exit 2
fi

case "$PROFILE" in
  core|standard|extended) ;;
  *)
    echo "Error: invalid profile '$PROFILE' (expected core, standard, or extended)" >&2
    exit 2
    ;;
esac

REPO_ROOT="$(cd "$REPO_ROOT" && pwd)"

FRAGMENTS=("$REPO_ROOT/config/common.config" "$REPO_ROOT/profiles/core/profile.config")
if [[ "$PROFILE" == "standard" || "$PROFILE" == "extended" ]]; then
  FRAGMENTS+=("$REPO_ROOT/profiles/standard/profile.config")
fi
if [[ "$PROFILE" == "extended" ]]; then
  FRAGMENTS+=("$REPO_ROOT/profiles/extended/profile.config")
fi

if [[ -n "$EXPERIMENTAL" ]]; then
  if [[ "$EXPERIMENTAL" =~ [/\\] || "$EXPERIMENTAL" == *".."* ]]; then
    echo "Error: invalid experimental config name '$EXPERIMENTAL'" >&2
    exit 2
  fi
  EXP_FILE="$REPO_ROOT/config/experimental/${EXPERIMENTAL}.config"
  if [[ ! -f "$EXP_FILE" ]]; then
    echo "Error: experimental config fragment not found: $EXP_FILE" >&2
    exit 1
  fi
  FRAGMENTS+=("$EXP_FILE")
fi

for frag in "${FRAGMENTS[@]}"; do
  if [[ ! -f "$frag" ]]; then
    echo "Error: missing config fragment: $frag" >&2
    exit 1
  fi
done

mkdir -p "$(dirname "$OUTPUT")"

python3 - "$PROFILE" "${EXPERIMENTAL:-none}" "$OUTPUT" "${FRAGMENTS[@]}" <<'PY'
import pathlib
import re
import sys

profile = sys.argv[1]
experimental = sys.argv[2]
output_path = pathlib.Path(sys.argv[3])
fragments = [pathlib.Path(p) for p in sys.argv[4:]]

set_re = re.compile(r"^(CONFIG_[A-Za-z0-9_.+-]+)=(.*)$")
unset_re = re.compile(r"^#\s*(CONFIG_[A-Za-z0-9_.+-]+)\s+is not set\s*$")

# Preserve deterministic insertion order while letting later fragments override earlier ones.
ordered_entries: dict[str, str] = {}

for frag in fragments:
    for raw_line in frag.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line:
            continue
        m_set = set_re.match(line)
        if m_set:
            key = m_set.group(1)
            ordered_entries.pop(key, None)
            ordered_entries[key] = line
            continue
        m_unset = unset_re.match(line)
        if m_unset:
            key = m_unset.group(1)
            ordered_entries.pop(key, None)
            ordered_entries[key] = f"# {key} is not set"
            continue
        if line.startswith("#"):
            continue
        raise ValueError(f"Unrecognized Kconfig line in {frag}: {raw_line}")

lines = [
    "# Automatically generated by scripts/build/merge-config.sh — do not edit directly.",
    f"# Profile: {profile} | Experimental: {experimental}",
    f"# Sources: {', '.join(f.name if f.parent.name != 'profiles' else f.parent.name for f in fragments)}",
    "",
    *ordered_entries.values(),
    "",
]
output_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
PY
